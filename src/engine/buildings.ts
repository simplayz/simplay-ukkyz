/* ------------------------------------------------------------------ *
 * Structure catalogue — the build vocabulary of the simulation.
 * Shared by the palette UI, the three.js mesh factory and the server
 * validator so a placement can never disagree between tiers.
 * ------------------------------------------------------------------ */

export type BuildCategory = "habitat" | "food" | "industry" | "commerce" | "civic" | "network" | "defense" | "luxury";

export interface BuildKind {
  key: string;
  name: string;
  category: BuildCategory;
  /** credits at level 1 */
  cost: number;
  /** credits consumed per economy tick */
  upkeep: number;
  /** footprint in grid cells [w, d] before rotation */
  footprint: [number, number];
  /** metres per storey */
  floorHeight: number;
  storeys: number;
  color: string;
  roof: "flat" | "pitch" | "dome" | "none" | "panels";
  population: number;
  income: number;
  food: number;
  power: number;
  defense: number;
  prestige: number;
  /** minimum survey farm score for the parcel (food structures) */
  minFarm?: number;
  /** must touch a road to function */
  needsRoad?: boolean;
  blurb: string;
}

