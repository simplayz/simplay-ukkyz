export function footprintFor(kind: BuildKind, rot: number): [number, number] {
  const [w, d] = kind.footprint;
  return rot % 2 === 0 ? [w, d] : [d, w];
}

export function buildingHeight(kind: BuildKind, level: number) {
  return Math.max(0.06, kind.floorHeight * (kind.storeys + Math.max(0, level - 1) * 0.5));
}

export function upgradeCost(kind: BuildKind, level: number) {
  return Math.round(kind.cost * 0.7 * Math.pow(1.55, level));
}

export function effectiveHeight(kind: BuildKind, level: number) {
  return buildingHeight(kind, level) * (1 + (level - 1) * 0.08);
}
